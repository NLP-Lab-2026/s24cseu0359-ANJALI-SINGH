"""Part E — Identify Language Segments"""

def identify_tokens(sentence):

    tokens = sentence.split()

    result = []

    for token in tokens:

        clean_token = re.sub(
            r'[^\w]',
            '',
            token
        )

        # Simple heuristic:
        # English/Roman-script token
        if re.fullmatch(
            r'[A-Za-z]+',
            clean_token
        ):
            language = "Roman/English"

        else:
            language = "Indic/Other"

        result.append(
            [token, language]
        )

    return result

"""# Apply to all **sentences**"""

