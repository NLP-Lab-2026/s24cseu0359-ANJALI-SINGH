import nltk
import pandas as pd
import numpy as np
import re
import math

from collections import Counter
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize

nltk.download('punkt')
nltk.download('punkt_tab')
nltk.download('stopwords')

"""Cell 2 — Create **Corpus**"""

documents = [
    "Machine learning is a powerful technology for data analysis.",
    "Deep learning is a branch of machine learning.",
    "Data science uses machine learning for prediction.",
    "Artificial intelligence and machine learning are useful technologies.",
    "Python is widely used for machine learning and data science."
]

print("Number of documents:", len(documents))

"""Cell 3 — **Preprocessing**"""

stop_words = set(stopwords.words('english'))

def preprocess(text):
    text = text.lower()

    tokens = word_tokenize(text)

    tokens = [
        word for word in tokens
        if word.isalpha() and word not in stop_words
    ]

    return tokens

processed_documents = [
    preprocess(doc)
    for doc in documents
]

for i, doc in enumerate(processed_documents, 1):
    print("Document", i, ":", doc)

"""Cell 4 — **Vocabulary**"""

vocabulary = sorted(
    set(
        word
        for doc in processed_documents
        for word in doc
    )
)

print("Vocabulary:")
print(vocabulary)

print("\nVocabulary Size:", len(vocabulary))

"""Cell 5 — TF **Matrix**"""

def calculate_tf(tokens, vocabulary):

    word_count = Counter(tokens)
    total_words = len(tokens)

    tf = {}

    for word in vocabulary:
        tf[word] = word_count[word] / total_words

    return tf


tf_matrix = []

for doc in processed_documents:

    tf = calculate_tf(doc, vocabulary)
    tf_matrix.append(tf)

tf_df = pd.DataFrame(
    tf_matrix,
    index=[f"Document {i}" for i in range(1, 6)]
)

tf_df

"""Cell 6 — **IDF**"""

N = len(processed_documents)

idf_values = {}

for word in vocabulary:

    document_frequency = sum(
        1
        for doc in processed_documents
        if word in doc
    )

    idf_values[word] = math.log(
        N / document_frequency
    )

idf_df = pd.DataFrame(
    list(idf_values.items()),
    columns=["Term", "IDF"]
)

idf_df

"""Cell 7 — TF-IDF **Matrix**"""

tfidf_matrix = []

for doc in processed_documents:

    row = {}

    tf = calculate_tf(doc, vocabulary)

    for word in vocabulary:
        row[word] = tf[word] * idf_values[word]

    tfidf_matrix.append(row)

tfidf_df = pd.DataFrame(
    tfidf_matrix,
    index=[f"Document {i}" for i in range(1, 6)]
)

tfidf_df

"""Cell 8 — Most Important **Terms**"""

for i in range(len(tfidf_df)):

    top_terms = (
        tfidf_df.iloc[i]
        .sort_values(ascending=False)
        .head(3)
    )

    print(f"\nDocument {i+1} - Important Terms:")

    for term, score in top_terms.items():
        print(term, ":", round(score, 4))

