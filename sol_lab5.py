"""Cell 3 — Word **Frequency**"""

all_words = [
    word
    for sentence in processed_sentences
    for word in sentence
]

word_frequency = Counter(all_words)

top_words = word_frequency.most_common(10)

top_words_df = pd.DataFrame(
    top_words,
    columns=["Word", "Frequency"]
)

top_words_df

"""Cell 4 — Create Co-occurrence **Matrix**"""

selected_words = [
    word
    for word, frequency in top_words
]

cooccurrence_matrix = np.zeros(
    (
        len(selected_words),
        len(selected_words)
    )
)

word_index = {
    word: i
    for i, word in enumerate(selected_words)
}

for sentence in processed_sentences:

    words_in_sentence = [
        word
        for word in sentence
        if word in word_index
    ]

    for word in words_in_sentence:

        for context_word in words_in_sentence:

            if word != context_word:

                i = word_index[word]
                j = word_index[context_word]

                cooccurrence_matrix[i][j] += 1

"""Cell 5 — Display Co-occurrence **Matrix**"""

cooccurrence_df = pd.DataFrame(
    cooccurrence_matrix,
    index=selected_words,
    columns=selected_words
)

cooccurrence_df

"""Cell 6 — Word **Vectors**"""

